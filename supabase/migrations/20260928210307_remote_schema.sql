CREATE OR REPLACE FUNCTION public.boost_clock (
  target uuid,
  amount integer
)
  RETURNS json
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
DECLARE
  v_boost_count bigint;
  v_level integer;
  v_amount integer := amount;
  v_drop_today date := (now() at time zone 'UTC')::date;
  v_quota integer := 10 + (((floor(extract(epoch from v_drop_today) / 86400)::bigint % 11) + 11) % 11);
  v_drop_used integer;
  v_missed integer;
  v_is_owner boolean;
BEGIN
  SELECT c.user_id = auth.uid(), b.drop_used, b.missed
    INTO v_is_owner, v_drop_used, v_missed
  FROM public.clocks c
    LEFT JOIN public.clock_boosts b ON b.clock_id = c.id
  WHERE c.id = target;

  IF v_is_owner IS NULL THEN
    RAISE EXCEPTION 'Clock not found';
  END IF;

  v_drop_used := COALESCE(v_drop_used, 0);
  v_missed   := COALESCE(v_missed, 0);

  IF v_is_owner THEN
    IF v_amount > v_quota - v_drop_used THEN
      v_amount := GREATEST(0, v_quota - v_drop_used);
    END IF;
    v_drop_used := v_drop_used + v_amount;
  ELSE
    IF v_missed > 0 THEN
      v_missed := v_missed - 1;
    END IF;
  END IF;

  INSERT INTO public.follows (user_id, clock_id, boost_count)
  VALUES (auth.uid(), target, 0)
  ON CONFLICT (user_id, clock_id)
  DO UPDATE SET boost_count = public.follows.boost_count + v_amount
  RETURNING boost_count INTO v_boost_count;

  UPDATE public.clocks
     SET boost_count = boost_count + v_amount,
         level = public.quest_level(boost_count + v_amount)
   WHERE id = target
  RETURNING boost_count, level INTO v_boost_count, v_level;

  INSERT INTO public.clock_boosts (clock_id, drop_day, drop_used, missed)
  VALUES (target, v_drop_today, v_drop_used, v_missed)
  ON CONFLICT (clock_id)
  DO UPDATE SET drop_day = excluded.drop_day,
                drop_used = CASE
                  WHEN excluded.drop_day > public.clock_boosts.drop_day THEN excluded.drop_used
                  ELSE GREATEST(public.clock_boosts.drop_used, excluded.drop_used)
                  END,
                missed = excluded.missed;

  RETURN json_build_object(
    'boost_count', v_boost_count,
    'level', v_level,
    'drop_day', v_drop_today,
    'drop_used', v_drop_used,
    'missed', v_missed
  );
END;
$function$;

REVOKE ALL ON FUNCTION "public"."boost_clock"(uuid, integer) FROM PUBLIC, "anon", "service_role";

CREATE OR REPLACE FUNCTION public.count_clock_boosters (
  clock_ids uuid[]
)
  RETURNS TABLE (
    clock_id uuid,
    boosters bigint
  )
  LANGUAGE sql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
  SELECT f.clock_id, COUNT(DISTINCT f.user_id)::bigint AS boosters
  FROM follows f
  JOIN clocks c ON c.id = f.clock_id
  WHERE f.boost_count > 0
    AND c.user_id = auth.uid()
    AND f.clock_id = ANY(clock_ids)
  GROUP BY f.clock_id;
$function$;

