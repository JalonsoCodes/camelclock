CREATE OR REPLACE FUNCTION public.quest_level (
  p_boost_count bigint
)
  RETURNS integer
  LANGUAGE sql
  IMMUTABLE
  SET search_path TO 'public'
  AS $function$
  SELECT CASE
    WHEN p_boost_count >= 500 THEN 10
    WHEN p_boost_count >= 390 THEN 9
    WHEN p_boost_count >= 300 THEN 8
    WHEN p_boost_count >= 225 THEN 7
    WHEN p_boost_count >= 165 THEN 6
    WHEN p_boost_count >= 115 THEN 5
    WHEN p_boost_count >= 75  THEN 4
    WHEN p_boost_count >= 45  THEN 3
    WHEN p_boost_count >= 25  THEN 2
    WHEN p_boost_count >= 10  THEN 1
    ELSE 0
  END;
$function$;

REVOKE ALL ON FUNCTION "public"."quest_level"(bigint) FROM "anon", "authenticated", "service_role";

CREATE OR REPLACE FUNCTION public.quest_level (
  p_boosts   integer,
  p_boosters integer,
  p_w48      integer,
  p_w72      integer
)
  RETURNS integer
  LANGUAGE sql
  IMMUTABLE
  PARALLEL SAFE
  AS $function$
    select least(10, (select count(*)::int + 1 from (
        select 1
        from (values
            (10, 0, null, null),
            (25, 1, null, null),
            (45, 2, null, null),
            (75, 3, null, null),
            (115, 4, 8, null),
            (165, 4, null, null),
            (225, 5, null, null),
            (300, 5, null, 15),
            (390, 6, null, null),
            (500, 7, null, 20)
        ) as q(b, br, w48, w72)
        where p_boosts >= q.b
          and p_boosters >= q.br
          and (q.w48 is null or p_w48 >= q.w48)
          and (q.w72 is null or p_w72 >= q.w72)
    ) s));
$function$;

REVOKE ALL ON FUNCTION "public"."quest_level"(integer, integer, integer, integer) FROM PUBLIC, "service_role";

CREATE OR REPLACE FUNCTION public.rls_auto_enable()
  RETURNS event_trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'pg_catalog'
  AS $function$
DECLARE
  cmd record;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        EXECUTE format('alter table if exists %s enable row level security', cmd.object_identity);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$function$;

REVOKE ALL ON FUNCTION "public"."rls_auto_enable"() FROM "anon", "authenticated", "service_role";

