CREATE OR REPLACE FUNCTION public.enforce_live_clock_limit()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
declare
    live_count integer;
    is_admin boolean;
begin
    if new.status <> 'live' or coalesce(old.status, 'draft') = 'live' then
        return new;
    end if;

    select p.is_admin into is_admin
    from public.profiles p
    where p.id = auth.uid();

    if coalesce(is_admin, false) then
        return new;
    end if;

    select count(*) into live_count
    from public.clocks c
    where c.user_id = auth.uid()
      and c.status = 'live'
      and c.id <> new.id;

    if live_count >= 3 then
        raise exception 'Live clock limit reached (3)';
    end if;

    return new;
end;
$function$;

REVOKE ALL ON FUNCTION "public"."enforce_live_clock_limit"() FROM "anon", "authenticated", "service_role";

CREATE OR REPLACE FUNCTION public.enforce_waitlist_rate_limit()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
declare
    recent integer;
begin
    select count(*) into recent
    from public.waitlist w
    where w.created_at > now() - interval '1 minute';

    if recent >= 20 then
        raise exception 'Waitlist is busy right now. Please try again shortly.';
    end if;

    return new;
end;
$function$;

